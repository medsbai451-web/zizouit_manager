// Owner-only provisioning. Uses the Firebase CLI login; never writes OAuth tokens
// or service-account credentials into the app. Does not send email or enable billing.
const fs = require('node:fs');
const path = require('node:path');
const cliRoot = '../firebase_tests/node_modules/firebase-tools/lib/';
const { logger } = require(cliRoot + 'logger');
logger.silent = true;
const auth = require(cliRoot + 'auth');
const { requireAuth } = require(cliRoot + 'requireAuth');
const api = require(cliRoot + 'api');
const apps = require(cliRoot + 'management/apps');
const [action, projectId, email] = process.argv.slice(2);
const root = path.resolve(__dirname, '..');
let token;
async function request(url, method = 'GET', body) {
  const response = await fetch(url, {
    method, headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const data = await response.json();
  if (!response.ok) throw Error(`${method} ${new URL(url).pathname}: ${response.status} ${data.error?.message || 'Request failed'}`);
  return data;
}
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
async function enableService(number, service) {
  const prefix = `https://serviceusage.googleapis.com/v1/projects/${number}/services/${service}`;
  const existing = await request(prefix);
  if (existing.state === 'ENABLED') return;
  console.log(`Enabling ${service}...`);
  let operation = await request(prefix + ':enable', 'POST', {});
  for (let i = 0; !operation.done && i < 50; i++) {
    await delay(2000);
    operation = await request('https://serviceusage.googleapis.com/v1/' + operation.name);
  }
  if (!operation.done || operation.error) throw Error(`Enable ${service} did not complete: ${operation.error?.message || 'timeout'}`);
}
async function prepare() {
  const project = await request(`https://firebase.googleapis.com/v1beta1/projects/${projectId}`);
  for (const service of ['identitytoolkit.googleapis.com', 'firestore.googleapis.com', 'firebaserules.googleapis.com']) {
    await enableService(project.projectNumber, service);
  }
  const existing = await apps.listFirebaseApps(projectId, apps.AppPlatform.ANY);
  const android = existing.find(app => app.platform === 'ANDROID' && app.namespace === 'com.example.zizouit_manager')
    || existing.find(app => app.platform === 'ANDROID' && app.packageName === 'com.example.zizouit_manager')
    || await apps.createAndroidApp(projectId, { displayName: 'ZIZOUIT Android', packageName: 'com.example.zizouit_manager' });
  const web = existing.find(app => app.platform === 'WEB' && app.displayName === 'ZIZOUIT Web')
    || await apps.createWebApp(projectId, { displayName: 'ZIZOUIT Web' });
  const ios = existing.find(app => app.platform === 'IOS' && (app.namespace === 'com.example.zizouitManager' || app.bundleId === 'com.example.zizouitManager'))
    || await apps.createIosApp(projectId, { displayName: 'ZIZOUIT iOS', bundleId: 'com.example.zizouitManager' });
  const webConfig = await apps.getAppConfig(web.appId, apps.AppPlatform.WEB);
  const androidConfig = await apps.getAppConfig(android.appId, apps.AppPlatform.ANDROID);
  const androidJson = JSON.parse(Buffer.from(androidConfig.configFileContents, 'base64').toString('utf8'));
  const iosConfig = await apps.getAppConfig(ios.appId, apps.AppPlatform.IOS);
  const plist = Buffer.from(iosConfig.configFileContents, 'base64').toString('utf8');
  const iosKey = plist.match(/<key>API_KEY<\/key>\s*<string>([^<]+)<\/string>/)?.[1];
  if (!webConfig.apiKey || !iosKey) throw Error('SDK config did not contain required public client keys');
  const config = {
    FIREBASE_ENABLED: 'true', FIREBASE_WORKSPACE: 'zizouit', FIREBASE_PROJECT_ID: projectId,
    FIREBASE_API_KEY: webConfig.apiKey, FIREBASE_WEB_API_KEY: webConfig.apiKey,
    FIREBASE_ANDROID_API_KEY: androidJson.client[0].api_key[0].current_key, FIREBASE_IOS_API_KEY: iosKey,
    FIREBASE_MESSAGING_SENDER_ID: String(project.projectNumber), FIREBASE_WEB_APP_ID: web.appId,
    FIREBASE_ANDROID_APP_ID: android.appId, FIREBASE_IOS_APP_ID: ios.appId,
    FIREBASE_IOS_BUNDLE_ID: 'com.example.zizouitManager',
  };
  fs.writeFileSync(path.join(root, 'firebase_config.json'), JSON.stringify(config, null, 2) + '\n');
  fs.writeFileSync(path.join(root, '.firebaserc'), JSON.stringify({ projects: { default: projectId } }, null, 2) + '\n');
  const constants = Object.entries(config).filter(([key]) => key !== 'FIREBASE_ENABLED').map(([key, value]) =>
    `  static const ${key.replace(/^FIREBASE_/, '').toLowerCase().replace(/_([a-z])/g, (_, letter) => letter.toUpperCase())} = ${JSON.stringify(value)};`).join('\n');
  fs.writeFileSync(path.join(root, 'lib/firebase/firebase_defaults.dart'),
    '// Firebase public client SDK configuration, generated by tool/firebase_owner.cjs.\n// These values grant no administrator privileges. No private keys are included.\nclass FirebaseDefaults {\n' + constants + '\n}\n');
  console.log(`Client SDK configuration saved for ${projectId}: Android, iOS and web.`);
  const authConfig = await request(`https://identitytoolkit.googleapis.com/admin/v2/projects/${projectId}/config?updateMask=signIn.email`, 'PATCH', {
    signIn: { email: { enabled: true, passwordRequired: true } },
  });
  if (!authConfig.signIn?.email?.enabled) throw Error('Email/password provider was not enabled');
  console.log('Email/password authentication enabled.');
}
async function bootstrap() {
  if (!email || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) throw Error('Provide the explicitly chosen administrator email');
  const lookup = await request(`https://identitytoolkit.googleapis.com/v1/projects/${projectId}/accounts:lookup`, 'POST', { email: [email] });
  let user = lookup.users?.[0];
  if (!user) {
    user = await request('https://identitytoolkit.googleapis.com/v1/accounts:signUp', 'POST', {
      targetProjectId: projectId, email, displayName: 'ZIZOUIT Admin', emailVerified: false,
    });
    console.log('Admin Auth account created without a password. Set it privately through the app password-reset flow.');
  }
  const uid = user.localId;
  if (!uid) throw Error('No UID returned for administrator');
  const fields = { role: { stringValue: 'المدير' }, active: { booleanValue: true } };
  await request(`https://firestore.googleapis.com/v1/projects/${projectId}/databases/(default)/documents/workspaces/zizouit/members/${uid}`, 'PATCH', { fields });
  console.log(`Administrator assigned: ${email} (UID ${uid}). Email verification is required before data access.`);
}
async function main() {
  if (!['prepare', 'bootstrap', 'verify'].includes(action) || !/^[a-z][a-z0-9-]{4,29}$/.test(projectId || '')) throw Error('Usage: node tool/firebase_owner.cjs prepare|bootstrap|verify PROJECT_ID [ADMIN_EMAIL]');
  const account = auth.getGlobalDefaultAccount();
  if (!account) throw Error('Sign in through tool/firebase.cmd login first');
  await requireAuth({ ...account, project: projectId });
  token = (await auth.getAccessToken(account.tokens.refresh_token, api.getScopes())).access_token;
  if (action === 'prepare') await prepare();
  if (action === 'bootstrap') await bootstrap();
  if (action === 'verify') {
    const config = await request(`https://identitytoolkit.googleapis.com/admin/v2/projects/${projectId}/config`);
    const database = await request(`https://firestore.googleapis.com/v1/projects/${projectId}/databases/(default)`);
    const release = await request(`https://firebaserules.googleapis.com/v1/projects/${projectId}/releases/cloud.firestore`);
    const ruleset = await request(`https://firebaserules.googleapis.com/v1/${release.rulesetName}`);
    const deployed = ruleset.source?.files?.find(file => file.name === 'firestore.rules')?.content;
    const rulesMatch = deployed === fs.readFileSync(path.join(root, 'firestore.rules'), 'utf8').replaceAll('\r\n', '\n');
    if (!rulesMatch) throw Error('Deployed Firestore rules do not match the tested local file');
    const sites = await request(`https://firebasehosting.googleapis.com/v1beta1/projects/${projectId}/sites`);
    const summary = { projectId, emailPasswordEnabled: config.signIn?.email?.enabled === true,
      location: database.locationId, databaseType: database.type, testedRulesDeployed: rulesMatch,
      authHandlerSiteExists: sites.sites?.some(site => site.name.endsWith('/' + projectId)) === true };
    if (email) {
      const lookup = await request(`https://identitytoolkit.googleapis.com/v1/projects/${projectId}/accounts:lookup`, 'POST', { email: [email] });
      const user = lookup.users?.[0];
      if (!user) throw Error('Administrator Auth account is missing');
      const member = await request(`https://firestore.googleapis.com/v1/projects/${projectId}/databases/(default)/documents/workspaces/zizouit/members/${user.localId}`);
      summary.adminEmail = user.email;
      summary.adminRole = member.fields?.role?.stringValue;
      summary.adminActive = member.fields?.active?.booleanValue;
      summary.adminEmailVerified = user.emailVerified === true;
      if (summary.adminRole !== 'المدير' || !summary.adminActive) throw Error('Administrator membership is not active');
    }
    console.log(JSON.stringify(summary));
  }
}
main().catch(error => { console.error(error.message); process.exitCode = 1; });
