import fs from 'node:fs';

// Translation source columns: existing Darija | Standard Arabic | French.
const rows = fs.readFileSync('lib/l10n/translations.txt', 'utf8').trim().split(/\r?\n/);
const catalog = {};
for (const row of rows) {
  const columns = row.split('|').map(value => value.replaceAll('\\n', '\n'));
  if (columns.length !== 3 || columns.some(value => !value)) throw Error(`Invalid translation: ${row}`);
  const [key, ar, fr] = columns;
  if (catalog[key]) throw Error(`Duplicate translation: ${key}`);
  const count = value => value.split('{}').length - 1;
  if (count(key) !== count(ar) || count(key) !== count(fr)) throw Error(`Placeholder mismatch: ${key}`);
  catalog[key] = [ar, fr];
}
const dartString = value => JSON.stringify(value).replaceAll('$', '\\$');
fs.writeFileSync('lib/l10n/catalog.dart', '// Generated by tool/generate_translations.mjs. Edit translations.txt.\nconst translations = <String, List<String>>{\n' + Object.entries(catalog).map(([key, values]) => `  ${dartString(key)}: [${values.map(dartString).join(', ')}],`).join('\n') + '\n};\n');
console.log(`Generated ${Object.keys(catalog).length} translations in two languages.`);
